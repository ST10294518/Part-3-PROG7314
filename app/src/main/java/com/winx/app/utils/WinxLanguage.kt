fun translate(text: String, language: String): String = when (language) {
    "isiZulu (Zulu)", "zu", "zu-ZA" -> isiZulu[text] ?: text
    "Afrikaans", "af", "af-ZA" -> afrikaans[text] ?: text
    else -> text
}

/** Replace numbered placeholders in one pass, preserving names supplied as data. */
fun translateFormat(text: String, language: String, vararg args: Any?): String {
    val template = translate(text, language)
    return Regex("\\{(\\d+)\\}").replace(template) { match ->
        val index = match.groupValues[1].toInt()
        if (index in args.indices) args[index]?.toString() ?: "" else match.value
    }
}

fun savedWinxLanguage(context: Context): String = context
    .getSharedPreferences("winx_settings", Context.MODE_PRIVATE)
    .getString("language", "English (US)") ?: "English (US)"

/** Language remains a device preference; profile/biometric settings stay per user. */
@Composable
fun currentWinxLanguage(): String {
    val context = LocalContext.current
    val preferences = remember(context) {
        context.getSharedPreferences("winx_settings", Context.MODE_PRIVATE)
    }
    val state = remember(preferences) {
        mutableStateOf(preferences.getString("language", "English (US)") ?: "English (US)")
    }
    DisposableEffect(preferences) {
        val listener = android.content.SharedPreferences.OnSharedPreferenceChangeListener { _, key ->
            if (key == "language" || key == null) {
                state.value = preferences.getString("language", "English (US)") ?: "English (US)"
            }
        }
        preferences.registerOnSharedPreferenceChangeListener(listener)
        // Read again after registration to avoid missing an intervening change.
        state.value = preferences.getString("language", "English (US)") ?: "English (US)"
        onDispose { preferences.unregisterOnSharedPreferenceChangeListener(listener) }
    }
    return state.value
}

@Composable
fun T(text: String, vararg args: Any?): String =
    translateFormat(text, currentWinxLanguage(), *args)

/** For native dialogs and other callbacks, where a composable cannot be invoked. */
fun localise(context: Context, text: String, vararg args: Any?): String =
    translateFormat(text, savedWinxLanguage(context), *args)

@Composable
fun currentWinxLocale(): Locale = when (currentWinxLanguage()) {
    "isiZulu (Zulu)" -> Locale.forLanguageTag("zu-ZA")
    "Afrikaans" -> Locale.forLanguageTag("af-ZA")
    else -> Locale.forLanguageTag("en-ZA")
}

@Composable
fun winxGreeting(name: String): String = when (currentWinxLanguage()) {
    "isiZulu (Zulu)" -> "Sawubona $name!"
    "Afrikaans" -> "Goeiemôre $name!"
